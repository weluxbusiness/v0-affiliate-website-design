// Parse legacy slug format: best-{store}-{category}-deals
function parseLegacySlug(slug: string): { store: string; category: string } | null {
  const match = slug.match(/^best-(.+?)-(.+?)-deals$/)
  if (match) {
    return { store: match[1], category: match[2] }
  }
  return null
}

// Parse auto-generated blog slug and generate content
function parseAutoGeneratedSlug(slug: string): GeneratedBlogPost | null {
  const year = new Date().getFullYear()
  const month = new Date().toLocaleString('default', { month: 'long' }).toLowerCase()
  
  // Pattern: best-{brand}-deals-today
  const brandTodayMatch = slug.match(/^best-(\w+(?:-\w+)*)-deals-today$/)
  if (brandTodayMatch && !stores[brandTodayMatch[1].toLowerCase()]) {
    // Only match if not a legacy store pattern
    return generateBrandPost(brandTodayMatch[1], 'today')
  }
  
  // Pattern: best-{brand}-deals-week
  const brandWeekMatch = slug.match(/^best-(\w+(?:-\w+)*)-deals-week$/)
  if (brandWeekMatch) {
    return generateBrandPost(brandWeekMatch[1], 'week')
  }
  
  // Pattern: best-{brand}-deals-{month}-{year}
  const brandMonthMatch = slug.match(new RegExp(`^best-(\\w+(?:-\\w+)*)-deals-${month}-${year}$`))
  if (brandMonthMatch) {
    return generateBrandPost(brandMonthMatch[1], 'month')
  }
  
  // Pattern: best-{category}-deals-under-{price}-{year}
  const categoryPriceMatch = slug.match(/^best-(\w+(?:-\w+)*)-deals-under-(\d+)-(\d+)$/)
  if (categoryPriceMatch) {
    const category = categoryPriceMatch[1]
    const price = parseInt(categoryPriceMatch[2])
    const slugYear = parseInt(categoryPriceMatch[3])
    if (slugYear === year) {
      return generateCategoryPost(category, price)
    }
  }
  
  // Pattern: top-trending-deals-week-{week}-{year}
  const trendingMatch = slug.match(/^top-trending-deals-week-(\d+)-(\d+)$/)
  if (trendingMatch) {
    return generateTrendingPost()
  }
  
  return null
}

async function getDeals(storeName: string, categoryInfo: { searchTerms: string[] }): Promise<Deal[]> {
  const supabase = createAnonClient()
  
  const { data: storeDeals } = await supabase
    .from('deals')
    .select('*')
    .eq('is_active', true)
    .ilike('store', `%${storeName}%`)
    .order('discount_percentage', { ascending: false })
    .limit(30)
  
  if (!storeDeals) return []
  
  const filtered = storeDeals.filter(deal => {
    const text = `${deal.title} ${deal.description}`.toLowerCase()
    return categoryInfo.searchTerms.some(term => text.includes(term))
  })
  
  return filtered.length > 0 ? filtered.slice(0, 12) : storeDeals.slice(0, 12)
}

