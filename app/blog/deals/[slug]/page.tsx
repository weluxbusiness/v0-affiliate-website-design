// Extract headings for table of contents
function extractHeadings(content: string): { id: string; text: string; level: number }[] {
  const headings: { id: string; text: string; level: number }[] = []
  const lines = content.split('\n')
  
  lines.forEach((line) => {
    const h2Match = line.match(/^## (.+)$/)
    const h3Match = line.match(/^### (.+)$/)
    
    if (h2Match) {
      const text = h2Match[1].trim()
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
      headings.push({ id, text, level: 2 })
    } else if (h3Match) {
      const text = h3Match[1].trim()
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
      headings.push({ id, text, level: 3 })
    }
  })
  
  return headings
}

// Format article content with enhanced styling
function formatContent(content: string): string {
  let html = content
    .replace(/^### (.*$)/gm, (_, text) => {
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
      return `<h3 id="${id}" class="text-xl font-semibold mt-8 mb-4">${text}</h3>`
    })
    .replace(/^## (.*$)/gm, (_, text) => {
      const id = text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
      return `<h2 id="${id}" class="text-2xl font-bold mt-10 mb-4">${text}</h2>`
    })
    .replace(/^# (.*$)/gm, "")
    .replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" class="text-primary hover:underline">$1</a>')
    .replace(/^- (.*$)/gm, "<li>$1</li>")
    .replace(/^\d+\. (.*$)/gm, "<li>$1</li>")
    .replace(/\|([^|]+)\|/g, (match) => {
      const cells = match.split("|").filter(Boolean)
      return "<tr>" + cells.map((cell) => `<td class="border border-border px-4 py-2">${cell.trim()}</td>`).join("") + "</tr>"
    })
    .split("\n\n")
    .map((para) => {
      if (
        para.startsWith("<h") ||
        para.startsWith("<li") ||
        para.startsWith("<tr") ||
        para.trim() === ""
      ) {
        return para
      }
      if (para.includes("<li>")) {
        return `<ul class="list-disc list-inside space-y-1 my-4 text-muted-foreground">${para}</ul>`
      }
      return `<p class="my-4 leading-relaxed text-muted-foreground">${para}</p>`
    })
    .join("\n")

  return html
}

function getWeekNumber(): number {
  const now = new Date()
  const start = new Date(now.getFullYear(), 0, 1)
  const diff = now.getTime() - start.getTime()
  const oneWeek = 604800000
  return Math.ceil(diff / oneWeek)
}

